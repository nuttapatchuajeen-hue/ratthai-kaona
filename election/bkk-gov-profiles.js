      + (no != null ? '<span class="govcard-no-badge">เบอร์ ' + no + '</span>' : '')
      + '<div class="govcard-photo">' + photoHtml + '</div>'
      + '</div>'
      + '<div class="govcard-body">'
      + '<span class="govcard-party" style="background:' + color + '">' + party + '</span>'
      + '<h3 id="govcName">' + name + '</h3>'
