        secsHtml += '<div class="govcard-sec"><div class="govcard-sec-t"><svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><rect x="2" y="7" width="20" height="14" rx="2" ry="2"/><path d="M16 21V5a2 2 0 0 0-2-2h-4a2 2 0 0 0-2 2v16"/></svg>ประสบการณ์และผลงานสำคัญ</div><div class="govcard-sec-d">' + prof.exp + '</div></div>';
