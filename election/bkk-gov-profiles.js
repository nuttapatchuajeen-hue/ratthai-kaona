        secsHtml += '<div class="govcard-sec" style="background:var(--orange-soft);border-color:var(--orange-line)"><div class="govcard-sec-t" style="color:var(--orange-deep)"><svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"/><line x1="12" y1="16" x2="12" y2="12"/><line x1="12" y1="8" x2="12.01" y2="8"/></svg>วิสัยทัศน์และนโยบายเด่น</div><div class="govcard-sec-d" style="color:var(--ink)">' + prof.vision + '</div></div>';
