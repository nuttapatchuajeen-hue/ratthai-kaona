      secsHtml += '<div class="govcard-sec"><div class="govcard-sec-t"><svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"/><path d="M12 16v-4M12 8h.01"/></svg>ข้อมูลประวัติ</div><div class="govcard-sec-d" style="color:var(--muted)">การ์ดนี้แสดงผลคะแนนและสังกัดทางการเมืองที่ตรวจสอบได้จาก กกต./วิกิพีเดีย สามารถกดปุ่มด้านล่างเพื่อค้นหาประวัติและผลงานเพิ่มเติมใน Google ได้</div></div>';
