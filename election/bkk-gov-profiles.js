/* ฟังก์ชันดึงข้อมูลโปรไฟล์ (รองรับทั้งชื่อตรง, ชื่อไม่มีคำนำหน้า, หรือค้นหาตามเบอร์) */
window.getGovProfile = function (name, no) {
  if (!name && !no) return null;
  var dict = window.BKK_GOV_PROFILES || {};
  if (name && dict[name]) return dict[name];

  // ค้นหาโดยตัดคำนำหน้า (เช่น นาย, นางสาว, ดร., พล.ต.อ., พล.ต.ท., พล.ต., รศ.ดร., ม.ร.ว., ม.ล., ร.ต.อ., น.ต., พ.ต.อ., ศ., ศ.ดร., คุณหญิง)
  if (name) {
    var clean = String(name).replace(/^(นาย|นางสาว|นาง|ดร\.|พล\.ต\.อ\.|พล\.ต\.ท\.|พล\.ต\.|รศ\.ดร\.|ม\.ร\.ว\.|ม\.ล\.|ร\.ต\.อ\.|น\.ต\.|พ\.ต\.อ\.|ศ\.|ศ\.ดร\.|คุณหญิง)\s*/, '').trim();
    for (var k in dict) {
      var kClean = k.replace(/^(นาย|นางสาว|นาง|ดร\.|พล\.ต\.อ\.|พล\.ต\.ท\.|พล\.ต\.|รศ\.ดร\.|ม\.ร\.ว\.|ม\.ล\.|ร\.ต\.อ\.|น\.ต\.|พ\.ต\.อ\.|ศ\.|ศ\.ดร\.|คุณหญิง)\s*/, '').trim();
      if (kClean === clean || k.indexOf(clean) !== -1 || clean.indexOf(kClean) !== -1) {
        return dict[k];
      }
    }
  }

  // ค้นหาโดยเบอร์ผู้สมัคร (สำหรับปี 2569 เป็นหลัก)
  if (no != null) {
    var num = Number(no);
    for (var kn in dict) {
      if (dict[kn].no === num) return dict[kn];
    }
  }

  return null;
};

